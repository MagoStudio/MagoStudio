export type IconSet = keyof typeof iconRegistry;

export type IconName<T extends IconSet> = keyof (typeof iconRegistry)[T];

export function getIconLoader<T extends IconSet>(
  iconSet: T,
  iconName: IconName<T>
): (() => Promise<typeof import("*.svg")>) | undefined {
  const icon = iconRegistry[iconSet][iconName];
  return icon as (() => Promise<typeof import("*.svg")>) | undefined;
}
