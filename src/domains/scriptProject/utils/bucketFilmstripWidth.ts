const SMALL_FILMSTRIP_WIDTH = 200;
const MEDIUM_FILMSTRIP_WIDTH = 400;
const LARGE_FILMSTRIP_WIDTH = 800;
const EXTRA_LARGE_FILMSTRIP_WIDTH = 1600;

const FILMSTRIP_WIDTH_BUCKETS = [
  SMALL_FILMSTRIP_WIDTH,
  MEDIUM_FILMSTRIP_WIDTH,
  LARGE_FILMSTRIP_WIDTH,
  EXTRA_LARGE_FILMSTRIP_WIDTH
];

export const bucketFilmstripWidth = (desiredWidth: number): number =>
  FILMSTRIP_WIDTH_BUCKETS.find((bucket) => desiredWidth <= bucket) ??
  EXTRA_LARGE_FILMSTRIP_WIDTH;
