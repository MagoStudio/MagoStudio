export const getRenderGenerationType = (
  magoEngine: VideoEngine
): RenderGenerationType => getEngineFamily(magoEngine);

export const getMaskInputType = (
  type: RenderGenerationType,
  renderSettings: VideoSettings
): MaskInputType => {
  if (type !== "mask") return "N/A";
  const maskMode = renderSettings.mask_mode;
  if (
    maskMode === "prompt" ||
    maskMode === "visual_selection" ||
    maskMode === "prompt_and_visual_selection"
  ) {
    return maskMode;
  }
  return "N/A";
};

const trackEventWithAmplitude = <T extends BaseEventProperties>(
  eventName: string,
  properties: Omit<T, "timestamp">
): void => {
  amplitude.track(eventName, properties);
};

const trackEvent = <T extends BaseEventProperties>(
  eventName: string,
  properties: Omit<T, "timestamp">
): void => {
  trackEventWithAmplitude(eventName, properties);
};

